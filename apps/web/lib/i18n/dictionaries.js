export function localizeCategoryName(slugOrName, locale = DEFAULT_LOCALE) {
  if (!slugOrName) return '';
  const lang = normalizeLocale(locale);
  const key = String(slugOrName).trim().toLowerCase();
  if (lang === 'en') {
    return slugOrName === key && CATEGORY_TRANSLATIONS[key]?.en?.name
      ? CATEGORY_TRANSLATIONS[key].en.name
      : slugOrName;
  }
  return CATEGORY_TRANSLATIONS[key]?.vi?.name || slugOrName;
}

export function localizeCategoryDescription(slug, fallbackDescription, locale = DEFAULT_LOCALE) {
  const lang = normalizeLocale(locale);
  if (lang === 'en') return fallbackDescription || '';
  const key = String(slug || '').trim().toLowerCase();
  return CATEGORY_TRANSLATIONS[key]?.vi?.description || fallbackDescription || '';
}

export function localizeCategorySubtitle(slug, fallbackSubtitle, locale = DEFAULT_LOCALE) {
  const lang = normalizeLocale(locale);
  if (lang === 'en') return fallbackSubtitle || '';
  const key = String(slug || '').trim().toLowerCase();
  return CATEGORY_TRANSLATIONS[key]?.vi?.subtitle || fallbackSubtitle || '';
}

