export function formatAevoTitle(pageName) {
  const clean = typeof pageName === 'string' ? pageName.trim() : '';
  return clean ? `AEVO - ${clean}` : 'AEVO';
}

function getByPath(obj, path) {
  if (!obj || !path) return undefined;
  return String(path)
    .split('.')
    .reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);
}

export function translate(locale, key, params = {}) {
  const lang = normalizeLocale(locale);
  const dict = dictionaries[lang] || dictionaries.en;
  let template = getByPath(dict, key);
  if (template === undefined) {
    template = getByPath(dictionaries.en, key);
  }
  if (typeof template !== 'string') {
    return key;
  }
  return template.replace(/\{(\w+)\}/g, (_, token) =>
    params[token] !== undefined && params[token] !== null ? String(params[token]) : `{${token}}`
  );
}
