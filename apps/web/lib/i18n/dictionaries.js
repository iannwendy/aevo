export function normalizeLocale(input) {
  if (!input || typeof input !== 'string') return DEFAULT_LOCALE;
  const lower = input.trim().toLowerCase();
  if (lower === 'vi' || lower === 'vie' || lower.startsWith('vi-')) {
    return 'vi';
  }
  return 'en';
}

